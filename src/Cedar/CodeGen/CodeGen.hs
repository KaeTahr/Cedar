{-# LANGUAGE OverloadedStrings #-}
module Cedar.CodeGen.CodeGen
  ( emitHeader
  , emitImpl
  ) where

import Data.Char (toUpper)
import Data.List (intercalate, scanl')
import Data.Bits (shiftL)
import Cedar.CodeGen.Allocation (AlignedBitRange(..))
import Cedar.Layout.ToCodeGen (CGStruct(..), CGField(..))
import Cedar.Layout.Surface (Endianness(..))
import Cedar.Compat.Basic (Size(..))

-- ===== helpers for sizes/types =====

totalBits :: [AlignedBitRange] -> Integer
totalBits = sum . map bitSizeABR

uRetTy :: Integer -> String
uRetTy n | n <= 32   = "uint32_t"
         | otherwise = "uint64_t"

sRetTy :: Integer -> String
sRetTy n | n <= 32   = "int32_t"
         | otherwise = "int64_t"

-- Given field endianness ω and the bit-sizes of each part (low→high order),
-- return the shift offsets to place each part inside the whole value.
shiftsFor :: Endianness -> [Int] -> [Int]
shiftsFor ω sizes =
  let leOffs = scanl (+) 0 sizes
      total  = sum sizes
      beShift le s = total - (le + s)
  in case ω of
       LE -> leOffs
       ME -> leOffs
       BE -> zipWith beShift leOffs sizes

-- mask for up to 32-bit parts (single word lane)
mask32 :: Integer -> Integer
mask32 n
  | n <= 0    = 0
  | n >= 32   = 0xFFFFFFFF
  | otherwise = (1 `shiftL` fromIntegral n) - 1

-- Given a bit offset into the concatenated value, return the size (in bits)
-- of the part that contains that offset.
sizeAtOff :: Integer -> [AlignedBitRange] -> Integer
sizeAtOff off ranges =
  let sizes   = map bitSizeABR ranges
      offsets = scanl' (+) 0 sizes   -- [0, s0, s0+s1, ...]
      idx     = length (takeWhile (< off) offsets)
  in  sizes !! idx

-- ===== public files =====

emitHeader :: CGStruct -> String
emitHeader (CGStruct typeName wordCount fields) =
  let guard nm = map (\c -> if c == ' ' then '_' else toUpper c) nm
      protoForField :: CGField -> [String]
      protoForField f =
        let w      = totalBits (cgRanges f)
            retTy  = if cgSigned f then sRetTy w else uRetTy w
        in  [ retTy ++ " d_get_" ++ cgName f ++ "(const " ++ typeName ++ " *b);"
            , "void d_set_" ++ cgName f ++ "(" ++ typeName ++ " *b, " ++ retTy ++ " v);"
            , ""
            ]
  in unlines
      [ "// This file is generated by Cedar"
      , ""
      , "#ifndef " ++ guard typeName ++ "__"
      , "#define " ++ guard typeName ++ "__"
      , ""
      , "#include <stdint.h>"
      , ""
      , "struct " ++ typeName ++ " {"
      , "  unsigned int data[" ++ show wordCount ++ "U];"
      , "};"
      , "typedef struct " ++ typeName ++ " " ++ typeName ++ ";"
      , ""
      ]
      ++ unlines (concatMap protoForField fields)
      ++ "#endif\n"

emitImpl :: CGStruct -> String
emitImpl (CGStruct typeName _ fields) =
  let toLower' c | 'A' <= c && c <= 'Z' = toEnum (fromEnum c + 32)
                 | otherwise            = c
  in unlines $
      [ "// This file is generated by Cedar"
      , ""
      , "#include <stdint.h>"
      , "#include <stddef.h>"
      , "#include \"" ++ map toLower' typeName ++ ".h\""
      , ""
      ]
      ++ concatMap (emitFieldFns typeName) fields

-- ===== per-field code =====

emitFieldFns :: String -> CGField -> [String]
emitFieldFns typeName (CGField fname brs ω isSigned) =
  let partGetNames = [ "d_get_" ++ fname ++ "_part" ++ show i | i <- [0..length brs - 1] ]
      partSetNames = [ "d_set_" ++ fname ++ "_part" ++ show i | i <- [0..length brs - 1] ]
      -- getters for each part (static, file-local)
      partGets  = zipWith (mkPartGet typeName) partGetNames brs
      -- final get that assembles them (endianness-aware + optional sign-extend)
      getFun    = mkWholeGet typeName ω isSigned fname partGetNames brs
      -- setters for each part (static, file-local)
      partSets  = zipWith (mkPartSet typeName) partSetNames brs
      -- final set that slices value (endianness-aware; mask using unsigned view)
      setFun    = mkWholeSet typeName ω isSigned fname partSetNames brs
  in partGets ++ [getFun] ++ partSets ++ [setFun]

  where
    mkPartGet :: String -> String -> AlignedBitRange -> String
    mkPartGet tn nm (AlignedBitRange sz boff woff) =
      unlines
        [ "static uint32_t " ++ nm ++ "(const " ++ tn ++ " *b)"
        , "{"
        , "  return ( (uint32_t)(b->data[" ++ show woff ++ "U]) >> " ++ show boff ++ "U) & "
              ++ show (mask32 sz) ++ "U;"
        , "}"
        ]

    mkWholeGet :: String -> Endianness -> Bool -> String -> [String] -> [AlignedBitRange] -> String
    mkWholeGet tn omega signedFlag nm partNs ranges =
      let sizes  = map (fromIntegral . bitSizeABR) ranges :: [Int]
          shifts = shiftsFor omega sizes
          totalI = sum sizes
          total  = fromIntegral totalI :: Integer
          uty    = uRetTy total
          sty    = sRetTy total
          -- assemble into a 64-bit unsigned accumulator
          terms  = zipWith
                     (\fn off -> "( (uint64_t)" ++ fn ++ "(b) << " ++ show off ++ "U )")
                     partNs
                     shifts
          assemble =
            [ uty ++ " acc_u = "
                ++ (if null terms then "0" else intercalate " | " terms) ++ ";"
            ]
          signExtend =
            if not signedFlag || total >= 64
              then [ "return (" ++ (if signedFlag then sty else uty) ++ ")acc_u;" ]
              else
                -- k-bit sign extension in 64-bit then cast to signed type
                let k      = show total
                    line1  = "uint64_t signbit = (uint64_t)1ULL << (" ++ k ++ " - 1U);"
                    line2  = "uint64_t acc_se = (acc_u ^ signbit) - signbit;"
                    retTy  = if signedFlag then sty else uty
                in  [ line1, line2, "return (" ++ retTy ++ ")acc_se;" ]
          retTy = if signedFlag then sty else uty
      in  unlines $
            [ retTy ++ " d_get_" ++ nm ++ "(const " ++ tn ++ " *b)"
            , "{"
            ] ++ assemble ++ signExtend ++ [ "}" ]

    mkPartSet :: String -> String -> AlignedBitRange -> String
    mkPartSet tn nm (AlignedBitRange sz boff woff) =
      unlines
        [ "static void " ++ nm ++ "(" ++ tn ++ " *b, uint32_t v)"
        , "{"
        , "  b->data[" ++ show woff ++ "U] ="
        , "      (b->data[" ++ show woff ++ "U] & ~(" ++ show (mask32 sz) ++ "U << " ++ show boff ++ "U))"
        , "    | (((" ++ show (mask32 sz) ++ "U & v) << " ++ show boff ++ "U));"
        , "}"
        ]

    mkWholeSet :: String -> Endianness -> Bool -> String -> [String] -> [AlignedBitRange] -> String
    mkWholeSet tn omega signedFlag nm partNs ranges =
      let sizes   = map (fromIntegral . bitSizeABR) ranges :: [Int]
          shifts  = shiftsFor omega sizes
          totalI  = sum sizes
          total   = fromIntegral totalI :: Integer
          argTy   = if signedFlag then sRetTy total else uRetTy total
          -- Always view v as uint64_t when slicing to avoid arithmetic right shift
          header  = [ "void d_set_" ++ nm ++ "(" ++ tn ++ " *b, " ++ argTy ++ " v)"
                    , "{"
                    , "  uint64_t vu = (uint64_t)v;"
                    ]
          lines'  = zipWith
                      (\n off ->
                        "  " ++ n ++ "(b, (uint32_t)((vu >> " ++ show off ++ "U) & "
                        ++ show (mask32 (sizeAtOff (fromIntegral off) ranges)) ++ "U));")
                      partNs
                      shifts
      in unlines $ header ++ lines' ++ [ "}", "" ]
